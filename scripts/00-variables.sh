#!/usr/bin/env bash
# =============================================================================
# Hybrid DNS lab: Azure DNS Private Resolver (Indonesia Central <-> Southeast Asia)
# 00-variables.sh: shared settings. Every step script sources this file.
# Run from Azure Cloud Shell (Bash), inside the scripts/ folder.
# Infrastructure: ../infra/main.bicep (subscription scope)
# =============================================================================
export DEPLOYMENT="dnslab"                 # subscription-scope deployment name
export LOC_ONP="indonesiacentral"          # simulated on-prem data centre
export LOC_AZ="southeastasia"              # Azure hub-spoke (also the deployment metadata location)
export RG_ONP="rg-dnslab-onprem-idc"
export RG_AZ="rg-dnslab-azure-sea"

export VM_DC="vm-onprem-dc01";  export VM_APP="vm-spoke-app01"
export DC_IP="10.10.1.4";       export APP_IP="10.21.1.4";   export INBOUND_IP="10.20.0.4"
export DOMAIN="contoso.org"; export NETBIOS="CONTOSO"; export DOMAIN2="contoso.com"
export ADMIN_USER="labadmin"
export VM_SIZE="${VM_SIZE:-Standard_D2s_v5}"

# Secrets: generated once, kept in your Cloud Shell home (mode 600), never printed.
# main.bicepparam reads ADMIN_PASS and VPN_PSK with readEnvironmentVariable().
STATE="$HOME/.dnslab"
if [ ! -f "$STATE" ]; then
  umask 077
  {
    echo "export ADMIN_PASS='Lab-$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | head -c 16)!9a'"
    echo "export VPN_PSK='$(openssl rand -hex 24)'"
  } > "$STATE"
fi
# shellcheck disable=SC1090
source "$STATE"

# The storage account name is generated by Bicep (uniqueString); read it from the deployment outputs once available.
ST_NAME="$(az deployment sub show -n "$DEPLOYMENT" --query properties.outputs.storageAccountName.value -o tsv 2>/dev/null)"
export ST_NAME

echo "Subscription : $(az account show --query name -o tsv) ($(az account show --query id -o tsv))"
echo "Deployment   : $DEPLOYMENT   on-prem RG: $RG_ONP ($LOC_ONP)   Azure RG: $RG_AZ ($LOC_AZ)"
